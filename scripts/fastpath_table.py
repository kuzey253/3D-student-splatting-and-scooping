"""Derive the ν-aware fast-path table: where Option A is within EPS of the exact filtered kernel.

For each ν on a grid, the smallest size ratio ρ = λ_min(Σ)/s from which Option A's max abs error
(alpha units at |o| = 1) stays ≤ EPS for every larger ρ on the grid and every aspect ratio in
ASPECTS. Writes the table into mip_sss/fastpath_table.py, which mip_sss.design reads.

At runtime a component with tail parameter ν uses the entry of the largest grid ν_i ≤ ν. That is
conservative because, at fixed ρ, the error decreases with ν; the script checks this on the grid.

Usage: python scripts/fastpath_table.py
"""
import math
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mip_sss.kernels import option_a  # noqa: E402
from mip_sss.reference import lambda_integral  # noqa: E402
from mip_sss.testing import S_MIP, ray_points, rot_cov  # noqa: E402

torch.set_default_dtype(torch.float64)
EPS = 1e-3
MARGIN = 0.9  # entries require error ≤ MARGIN·EPS on the grid, leaving room between grid points
NUS = (1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 6.0, 8.0, 10.0, 12.0, 16.0, 20.0, 25.0, 30.0,
       40.0, 50.0, 70.0, 100.0, 150.0, 200.0, 300.0, 400.0, 500.0, 700.0, 1000.0)
RHOS = tuple(10 ** (k / 4) for k in range(-12, 15))  # 1e-3 … ~3e3, 4 per decade
ASPECTS = ((1.0, 0.0), (4.0, 0.6), (16.0, 1.1), (64.0, 2.3))


def max_error(nu, rho):
    worst = 0.0
    for ratio, th in ASPECTS:
        lam = rho * S_MIP
        cov = rot_cov((lam, ratio * lam), th)[None]
        u, mu, nut = ray_points(cov[0], nu, S_MIP), torch.zeros(1, 2), torch.tensor([nu])
        ref = lambda_integral(u, mu, cov, nut, S_MIP)[0]
        worst = max(worst, float((option_a(u, mu, cov, nut, S_MIP)[0] - ref).abs().max()))
    return worst


def main():
    errs = {}
    for nu in NUS:
        for rho in RHOS:
            errs[nu, rho] = max_error(nu, rho)
        print(f"ν={nu:g}: max err {max(errs[nu, r] for r in RHOS):.1e}")

    table = []
    for nu in NUS:
        thr = math.inf
        for rho in reversed(RHOS):
            if errs[nu, rho] > MARGIN * EPS:
                break
            thr = rho
        table.append((nu, 0.0 if thr == RHOS[0] else thr))

    # conservativeness of the step rule: at fixed ρ the error must not grow with ν
    violations = [(a, b, r) for (a, b) in zip(NUS, NUS[1:]) for r in RHOS
                  if errs[b, r] > errs[a, r] * 1.05 and errs[b, r] > EPS / 10]
    print("monotonicity violations (ν_i, ν_i+1, ρ):", violations or "none")

    lines = ['"""Generated by scripts/fastpath_table.py. Do not edit by hand.',
             "",
             f"(ν_i, ρ_i): for ν ≥ ν_i (up to the next entry), Option A is within {EPS:g} max abs",
             "error of the exact filtered kernel when λ_min(Σ)/s ≥ ρ_i. inf means never; 0 means",
             f"always. Entries need error ≤ {MARGIN:g}·EPS on the grid: aspect ratios",
             f"{[a for a, _ in ASPECTS]}, ρ in [{RHOS[0]:.0e}, {RHOS[-1]:.0e}] (4 per decade),",
             f"s = {S_MIP} px².",
             '"""',
             f"EPS = {EPS!r}",
             "TABLE = ("]
    lines += [f"    ({nu!r}, {'float(\"inf\")' if math.isinf(r) else repr(round(r, 6))})," for nu, r in table]
    lines += [")", ""]
    out = ROOT / "mip_sss" / "fastpath_table.py"
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
