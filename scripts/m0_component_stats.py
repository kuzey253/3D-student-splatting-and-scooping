"""M0: component statistics of a trained SSS model, and the design's expected rendering overhead.

Reads <model_dir>/point_cloud/iteration_*/point_cloud.ply and <model_dir>/cameras.json (as SSS
writes them), projects a subsample of components into a subsample of the cameras at 1/1, 1/2,
1/4 and 1/8 of the training resolution, and reports:
- the learned ν distribution (and how many sit at the clamp bounds or at the initial value);
- the distribution of ρ = λ_min(Σ_2D)/s per scale;
- the share of visible (component, view) pairs the design sends to Option B;
- an ESTIMATE of the kernel-evaluation cost relative to SSS: Σ tiles × 256 × (transcendentals
  per evaluation) over visible pairs, with SSS = 2 (pow), Option A = 2, Option B = 2K + 2. It
  ignores sorting, memory traffic and early termination, so treat it as a rough guide only.

Runs on CPU; needs no CUDA. Usage:
    python scripts/m0_component_stats.py <model_dir> [--out results/m0/<name>] [--components 200000]
"""
import argparse
import json
import math
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mip_sss import design  # noqa: E402
from mip_sss.analysis import (BLOCK, load_cameras, load_sss_model, project,  # noqa: E402
                              tiles_touched)
from mip_sss.kernels import eig2_min, sss_radius  # noqa: E402
from mip_sss.testing import S_MIP  # noqa: E402

torch.set_default_dtype(torch.float64)
SCALES = (1, 2, 4, 8)
NU_BINS = (1.0, 1.01, 1.5, 2, 3, 4, 6, 8, 12, 16, 30, 50, 99.99, 100.01, 300, 1000, 9999, 1e4 + 1)
RHO_BINS = (0, 1e-3, 1e-2, 1e-1, 1, 10, 100, 1e3, 1e4, math.inf)
# transcendentals per kernel evaluation: pow = log + exp; Option B's control variate costs two
# exps per node (g_k and h_k) plus Option A's pow
COST = {"sss": 2.0, "A": 2.0, "B": 2.0 * design.QUAD.K + 2}


def histogram(x, edges):
    return [int(((x >= lo) & (x < hi)).sum()) for lo, hi in zip(edges[:-1], edges[1:])]


def analyse(model, cameras, n_components, n_cameras, seed=0):
    g = torch.Generator().manual_seed(seed)
    n = model["xyz"].shape[0]
    idx = torch.randperm(n, generator=g)[:min(n, n_components)]
    xyz, cov3, nu, o = (model[k][idx] for k in ("xyz", "cov3", "nu", "opacity"))
    cams = [cameras[i] for i in torch.randperm(len(cameras), generator=g)[:n_cameras].tolist()]

    report = {"components_total": n, "components_sampled": len(idx), "cameras_used": len(cams),
              "iteration": model["iteration"], "nu": {}, "scales": {}}
    nu_all = model["nu"]
    report["nu"] = {
        "edges": list(NU_BINS), "counts": histogram(nu_all, NU_BINS),
        "median": float(nu_all.median()), "at_lower_bound_1": float((nu_all <= 1.0).double().mean()),
        "at_upper_bound_1e4": float((nu_all >= 1e4).double().mean()),
        "at_init_100": float(((nu_all - 100).abs() < 1e-3).double().mean()),
        "negative_opacity": float((model["opacity"] < 0).double().mean()),
    }
    for f in SCALES:
        rho_all, slow_pairs, pairs = [], 0, 0
        cost = {"sss": 0.0, "design": 0.0}
        for cam in cams:
            mean2, cov2, valid = project(xyz, cov3, cam, f)
            W, H = cam.width / f, cam.height / f
            r_sss = sss_radius(cov2, nu)
            on = valid & (tiles_touched(mean2, r_sss, W, H) > 0)
            if not on.any():
                continue
            c2, nu_v, o_v, m2 = cov2[on], nu[on], o[on], mean2[on]
            rho_all.append(eig2_min(c2) / S_MIP)
            fast = design.use_fast_path(c2, nu_v, S_MIP)
            r_des = design.radius(c2, nu_v, o_v, S_MIP)
            t_sss = tiles_touched(m2, r_sss[on], W, H)
            t_des = tiles_touched(m2, r_des, W, H)
            pairs += int(on.sum())
            slow_pairs += int((~fast).sum())
            per_eval = torch.where(fast, torch.full_like(nu_v, COST["A"]),
                                   torch.full_like(nu_v, COST["B"]))
            cost["sss"] += float((t_sss * BLOCK * BLOCK * COST["sss"]).sum())
            cost["design"] += float((t_des * BLOCK * BLOCK * per_eval).sum())
        rho = torch.cat(rho_all) if rho_all else torch.zeros(0)
        report["scales"][f"1/{f}"] = {
            "visible_pairs": pairs,
            "option_b_share": slow_pairs / pairs if pairs else float("nan"),
            "rho_edges": [str(e) for e in RHO_BINS], "rho_counts": histogram(rho, RHO_BINS),
            "estimated_eval_cost_vs_sss": cost["design"] / cost["sss"] if cost["sss"] else float("nan"),
        }
    return report


def markdown(report, name):
    nu = report["nu"]
    lines = [f"# M0 component statistics: {name}", "",
             f"Generated by `scripts/m0_component_stats.py`. Iteration {report['iteration']}; "
             f"{report['components_total']} components ({report['components_sampled']} sampled for "
             f"projection), {report['cameras_used']} cameras, s = {S_MIP} px².", "",
             "## Learned ν", "",
             f"Median {nu['median']:.3g}. At the lower bound 1: {nu['at_lower_bound_1']:.1%}; at the "
             f"upper bound 1e4: {nu['at_upper_bound_1e4']:.1%}; still at the initial 100: "
             f"{nu['at_init_100']:.1%}. Negative opacity: {nu['negative_opacity']:.1%}.", "",
             "| ν range | components |", "| --- | --- |"]
    e = nu["edges"]
    lines += [f"| [{e[i]:g}, {e[i + 1]:g}) | {c} |" for i, c in enumerate(nu["counts"])]
    lines += ["", "## Per scale", "",
              "| scale | visible pairs | Option B share | estimated eval cost vs SSS |",
              "| --- | --- | --- | --- |"]
    for k, s in report["scales"].items():
        lines.append(f"| {k} | {s['visible_pairs']} | {s['option_b_share']:.1%} | "
                     f"{s['estimated_eval_cost_vs_sss']:.2f}× (estimated) |")
    lines += ["", "## ρ = λ_min(Σ_2D)/s per scale (visible pairs)", "",
              "| ρ range | " + " | ".join(report["scales"]) + " |",
              "| --- |" + " --- |" * len(report["scales"])]
    edges = RHO_BINS
    for i in range(len(edges) - 1):
        lines.append(f"| [{edges[i]:g}, {edges[i + 1]:g}) | "
                     + " | ".join(str(s["rho_counts"][i]) for s in report["scales"].values()) + " |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model_dir")
    ap.add_argument("--iteration", type=int, default=None)
    ap.add_argument("--out", default=None, help="output directory (default results/m0/<model name>)")
    ap.add_argument("--components", type=int, default=200_000)
    ap.add_argument("--cameras", type=int, default=20)
    args = ap.parse_args()
    model = load_sss_model(args.model_dir, args.iteration)
    cameras = load_cameras(args.model_dir)
    name = Path(args.model_dir).resolve().name
    out = Path(args.out) if args.out else ROOT / "results" / "m0" / name
    out.mkdir(parents=True, exist_ok=True)
    report = analyse(model, cameras, args.components, args.cameras)
    (out / "component_stats.json").write_text(json.dumps(report, indent=1))
    (out / "component_stats.md").write_text(markdown(report, name))
    print(markdown(report, name))


if __name__ == "__main__":
    main()
