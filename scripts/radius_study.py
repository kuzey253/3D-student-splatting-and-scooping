"""M1 culling-radius study, at |o| = 1 and s = S_MIP.

Compares, per covariance case and ν:
- r_true: where the exact filtered kernel falls to 1/255 along the major axis (bisection);
- r_sss:  SSS's own rule (forward.cu) applied to the filtered covariance Σ + sI;
- r_B:    radius_option_b's conservative bound for each Option B candidate.
r_sss < r_true means the tile footprint cuts off visible alpha. The tile cost of a candidate
scales with r_B², reported relative to r_sss².

Usage: python scripts/radius_study.py
Writes results/m1/radius_study.md.
"""
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mip_sss import QuadConfig, design, radius_option_b  # noqa: E402
from mip_sss.kernels import sss_radius  # noqa: E402
from mip_sss.reference import lambda_integral  # noqa: E402
from mip_sss.testing import COV_CASES, S_MIP, rot_cov  # noqa: E402

torch.set_default_dtype(torch.float64)
OUT = ROOT / "results" / "m1"
NUS = (1.0, 1.5, 2.0, 3.5, 4.0, 8.0, 12.5, 30.0, 100.0)
ALPHA_MIN = 1 / 255
# Option B rules from the M1 comparison; "design" is the full chosen hybrid (design.radius)
CONFIGS = {
    "tail32_cvA": QuadConfig("adaptive_tail", 32, left=4.0, right=4.0, tail_tau=1e-4, control="A"),
    "tail12_cvA": design.QUAD,
    "gauss8": QuadConfig("gauss", 8),
    "gauss2_8_cvA": QuadConfig("gauss", 8, gauss_tail_nodes=4, left=1.0, control="A"),
}


def true_radius(cov, nu):
    evals, evecs = torch.linalg.eigh(cov)
    major = evecs[:, 1]
    mu, nut = torch.zeros(1, 2), torch.tensor([nu])

    def T(r):
        return float(lambda_integral((r * major)[None], mu, cov[None], nut, S_MIP)[0, 0])

    if T(0.0) < ALPHA_MIN:
        return 0.0
    lo, hi = 0.0, 1.0
    while T(hi) >= ALPHA_MIN:
        lo, hi = hi, hi * 2
    for _ in range(50):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if T(mid) >= ALPHA_MIN else (lo, mid)
    return hi


def main():
    names = list(CONFIGS)
    lines = ["# M1 culling-radius study", "",
             f"Generated by `scripts/radius_study.py`. |o| = 1, s = {S_MIP} px². Radii in px. "
             "`r_sss` is SSS's rule on Σ + sI; `cut` marks r_sss < r_true (visible alpha is cut "
             "off). The other columns give each radius and, in brackets, the tile-area ratio to "
             "r_sss². Option B columns use the bound for that rule alone; `design` is the chosen "
             "hybrid (Option A's exact radius where it takes the fast path).",
             "",
             "| eigenvalues of Σ | ν | r_true | r_sss | " + " | ".join(names) + " | design |",
             "| --- | --- | --- | --- |" + " --- |" * (len(names) + 1)]
    for eigs, th in COV_CASES:
        cov = rot_cov(eigs, th)
        filt = cov + S_MIP * torch.eye(2)
        for nu in NUS:
            nut, o = torch.tensor([nu]), torch.ones(1)
            rt = true_radius(cov, nu)
            rs = float(sss_radius(filt[None], nut)[0])
            cells = []
            for n in names:
                rb = float(radius_option_b(cov[None], nut, o, S_MIP, CONFIGS[n], ALPHA_MIN)[0])
                cells.append(f"{rb:.1f} ({rb ** 2 / rs ** 2:.1f}×)")
            rd = float(design.radius(cov[None], nut, o, S_MIP, ALPHA_MIN)[0])
            cells.append(f"{rd:.1f} ({rd ** 2 / rs ** 2:.1f}×)")
            cut = " cut" if rs < rt else ""
            lines.append(f"| {eigs} | {nu:g} | {rt:.2f} | {rs:.0f}{cut} | " + " | ".join(cells) + " |")
        print(f"{eigs} done")
    (OUT / "radius_study.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT / 'radius_study.md'}")


if __name__ == "__main__":
    main()
