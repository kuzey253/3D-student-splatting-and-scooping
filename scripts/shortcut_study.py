"""M1 shortcut study: where are the closed forms (Option A, Option A', Gaussian) accurate enough?

For each ν and size ratio ρ = λ_min(Σ)/s, the max abs error (alpha units at |o| = 1) of each
closed form against the exact filtered kernel, worst over anisotropy (1:1, 1:4) and rotation.
From that, the smallest ρ above which each shortcut stays within ε, per ν: the ν-aware fast-path
threshold for the hybrid (README's default is ρ > 10 for every ν).

Usage: python scripts/shortcut_study.py
Writes results/m1/shortcut_study.csv and results/m1/shortcut_study.md.
"""
import csv
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mip_sss.kernels import closed_form  # noqa: E402
from mip_sss.reference import lambda_integral  # noqa: E402
from mip_sss.testing import NUS_EXTENDED, S_MIP, ray_points, rot_cov  # noqa: E402

torch.set_default_dtype(torch.float64)
OUT = ROOT / "results" / "m1"
RHOS = (0.1, 0.3, 1.0, 3.0, 10.0, 30.0, 100.0, 300.0, 1000.0)
SHAPES = ((1.0, 0.0), (4.0, 0.6))  # (λ_max/λ_min, rotation)
SHORTCUTS = ("A", "A_prime", "gaussian")
EPS = (1e-3, 1 / 255)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for nu in NUS_EXTENDED:
        for rho in RHOS:
            worst = dict.fromkeys(SHORTCUTS, 0.0)
            for ratio, th in SHAPES:
                lam_min = rho * S_MIP
                cov = rot_cov((lam_min, ratio * lam_min), th)[None]
                u, mu, nut = ray_points(cov[0], nu, S_MIP), torch.zeros(1, 2), torch.tensor([nu])
                ref = lambda_integral(u, mu, cov, nut, S_MIP)[0]
                for name in SHORTCUTS:
                    err = (closed_form(name, u, mu, cov, nut, S_MIP)[0] - ref).abs().max()
                    worst[name] = max(worst[name], float(err))
            rows.append(dict(nu=nu, rho=rho, **worst))
        print(f"ν={nu:g} done")

    with open(OUT / "shortcut_study.csv", "w", newline="") as f:
        w = csv.DictWriter(f, ["nu", "rho", *SHORTCUTS])
        w.writeheader()
        w.writerows(rows)

    def threshold(nu, name, eps):
        """Smallest ρ in RHOS such that the error is ≤ eps at that ρ and every larger one."""
        errs = [(r["rho"], r[name]) for r in rows if r["nu"] == nu]
        ok = None
        for rho, e in reversed(errs):
            if e > eps:
                break
            ok = rho
        return "never" if ok is None else f"{ok:g}"

    names = {"A": "Option A", "A_prime": "Option A'", "gaussian": "Gaussian (README fallback)"}
    lines = ["# M1 shortcut study", "",
             f"Generated by `scripts/shortcut_study.py`. s = {S_MIP} px². ρ = λ_min(Σ)/s. Max abs "
             "error against the exact filtered kernel, worst over aspect ratios 1:1 and 1:4. "
             "One 8-bit step is 1/255 ≈ 3.9e-3.", ""]
    for name in SHORTCUTS:
        lines += [f"## {names[name]}: max abs error", "",
                  "| ν | " + " | ".join(f"ρ={r:g}" for r in RHOS) + " |",
                  "| --- |" + " --- |" * len(RHOS)]
        for nu in NUS_EXTENDED:
            vals = {r["rho"]: r[name] for r in rows if r["nu"] == nu}
            lines.append(f"| {nu:g} | " + " | ".join(f"{vals[r]:.1e}" for r in RHOS) + " |")
        lines.append("")
    lines += ["## Fast-path threshold: smallest ρ from which the error stays within ε", "",
              "| ν | " + " | ".join(f"{names[n]}, ε={e:.1e}" for n in SHORTCUTS for e in EPS) + " |",
              "| --- |" + " --- |" * (len(SHORTCUTS) * len(EPS))]
    for nu in NUS_EXTENDED:
        lines.append(f"| {nu:g} | " + " | ".join(threshold(nu, n, e) for n in SHORTCUTS for e in EPS)
                     + " |")
    (OUT / "shortcut_study.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT / 'shortcut_study.md'}")


if __name__ == "__main__":
    main()
