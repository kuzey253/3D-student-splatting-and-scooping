"""Run the test suite and tabulate passed/run per test function.

Usage: python scripts/test_matrix.py
Writes results/m1/test_matrix.md.
"""
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "m1"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    xml = Path(tempfile.mkdtemp()) / "pytest.xml"
    subprocess.run([sys.executable, "-m", "pytest", str(ROOT / "tests"), "-q", "--tb=no",
                    "-p", "no:cacheprovider", f"--junitxml={xml}"], cwd=ROOT)
    counts = defaultdict(lambda: [0, 0, 0])  # passed, failed, skipped
    for case in ET.parse(xml).getroot().iter("testcase"):
        key = f"{case.get('classname').split('.')[-1]}::{case.get('name').partition('[')[0]}"
        if case.find("failure") is not None or case.find("error") is not None:
            counts[key][1] += 1
        elif case.find("skipped") is not None:
            counts[key][2] += 1
        else:
            counts[key][0] += 1
    lines = ["# Test matrix", "",
             "Generated by `scripts/test_matrix.py`: passed/run per test function (skips excluded), "
             "for the design chosen at the M1 gate (`mip_sss/design.py`).", "",
             "| test | passed/run |", "| --- | --- |"]
    for key in sorted(counts):
        p, f, _ = counts[key]
        lines.append(f"| {key} | {p}/{p + f}{' ✗' if f else ''} |")
    tot = [sum(v[i] for v in counts.values()) for i in range(3)]
    lines += ["", f"Total: {tot[0]} passed, {tot[1]} failed, {tot[2]} skipped."]
    (OUT / "test_matrix.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
